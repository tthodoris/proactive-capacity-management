/** Physical/regional locations commonly used as deployment targets (excludes geo aggregates). */
const GEO_AGGREGATES = new Set([
  'asia',
  'asiapacific',
  'australia',
  'brazil',
  'canada',
  'europe',
  'france',
  'germany',
  'global',
  'india',
  'japan',
  'korea',
  'norway',
  'singapore',
  'southafrica',
  'switzerland',
  'uae',
  'uk',
  'unitedstates',
  'unitedstateseuap',
])

export function deployableAzureRegions(
  extra: AzureRegionCatalogEntry[] = [],
): AzureRegionCatalogEntry[] {
  const map = new Map<string, AzureRegionCatalogEntry>()
  for (const region of [...AZURE_PUBLIC_REGIONS, ...extra]) {
    const id = String(region.id || '')
      .toLowerCase()
      .trim()
    if (!id || GEO_AGGREGATES.has(id)) continue
    if (id.endsWith('stage') || id.endsWith('stg') || id.endsWith('euap')) continue
    map.set(id, { id, label: region.label || id })
  }
  return [...map.values()].sort((a, b) => a.label.localeCompare(b.label))
}
